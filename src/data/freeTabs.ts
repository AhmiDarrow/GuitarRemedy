import type { LibraryItem, TabSong } from './library'

function m(notes: Array<[number, number, number?]>): { notes: Array<{ string: number; fret: number; duration: number }> } {
  return {
    notes: notes.map(([string, fret, duration = 1]) => ({ string, fret, duration })),
  }
}

function song(
  title: string,
  tempo: number,
  measures: TabSong['measures'],
  timeSig: [number, number] = [4, 4],
): TabSong {
  return { title, tempo, timeSig, measures }
}

